export function searchSpecies(query: string, limit = 8): SpeciesInfo[] {
  const q = query.trim().toLowerCase();
  if (!q) return SPECIES_INDEX.slice(0, limit);
  return SPECIES_INDEX.filter((s) => s.name.toLowerCase().includes(q)).slice(
    0,
    limit,
  );
}

export function findSpecies(name: string): SpeciesInfo | undefined {
  const q = name.trim().toLowerCase();
  return SPECIES_INDEX.find((s) => s.name.toLowerCase() === q);
}
