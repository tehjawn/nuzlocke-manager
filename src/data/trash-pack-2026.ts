function ivs(partial: Partial<StatSpread>): StatSpread {
  return {
    hp: 31,
    atk: 31,
    def: 31,
    spa: 31,
    spd: 31,
    spe: 31,
    ...partial,
  };
}

function evs(partial: Partial<StatSpread>): StatSpread {
  return {
    hp: 0,
    atk: 0,
    def: 0,
    spa: 0,
    spd: 0,
    spe: 0,
    ...partial,
  };
}

function mon(
  partial: Omit<PokemonEntry, "id"> & { id?: string },
): PokemonEntry {
  return {
    id: partial.id ?? `${partial.slot}-${partial.partyIndex}-${partial.species}`,
    ...partial,
  };
}

function trainer(
  partial: Omit<
    TrainerProfile,
    | "pokemon"
    | "userId"
    | "updatedAt"
    | "discordUsername"
    | "discordDisplayName"
  > & {
    pokemon?: PokemonEntry[];
    userId?: string | null;
    updatedAt?: string | null;
    discordUsername?: string | null;
    discordDisplayName?: string | null;
  },
): TrainerProfile {
  return {
    ...partial,
    userId: partial.userId ?? null,
    updatedAt: partial.updatedAt ?? null,
    discordUsername: partial.discordUsername ?? null,
    discordDisplayName: partial.discordDisplayName ?? null,
    pokemon: partial.pokemon ?? [],
  };
}

