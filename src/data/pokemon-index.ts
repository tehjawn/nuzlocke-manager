export function searchPokemonIndex(query: string, limit = 80): PokemonIndexEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return POKEMON_INDEX.slice(0, limit);
  const asNum = Number(q);
  if (Number.isFinite(asNum) && asNum > 0) {
    return POKEMON_INDEX.filter((p) => p.pokedexId === asNum).slice(0, limit);
  }
  return POKEMON_INDEX.filter(
    (p) => p.name.toLowerCase().includes(q) || p.slug.includes(q),
  ).slice(0, limit);
}

export function findPokemonById(id: number): PokemonIndexEntry | undefined {
  return POKEMON_INDEX.find((p) => p.pokedexId === id);
}
